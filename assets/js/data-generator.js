  function rand(min, max) {
    return Math.floor(Math.random() * (max - min + 1)) + min;
  }
  function jitter(base, range) {
    return base + (Math.random() - 0.5) * range;
  }
  function pick(arr, n) {
    var copy = arr.slice();
    var result = [];
    for (var i = 0; i < n && copy.length; i++) {
      var idx = Math.floor(Math.random() * copy.length);
      result.push(copy.splice(idx, 1)[0]);
    }
    return result;
  }

  function buildDescription(tplName, place) {
    // کلید رو از قالب پیدا کن
    var key = Object.keys(DESCRIPTIONS).find(function (k) {
      return tplName.indexOf(k) === 0;
    });
    if (!key) return '';
    return DESCRIPTIONS[key].replace(/\{place\}/g, place);
  }

